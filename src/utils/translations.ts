/**
 * 统一翻译函数，支持不区分大小写的查找
 */
export const translateCountry = (country: string | undefined): string => {
    if (!country) return '';
    // 优先尝试原始匹配，再尝试大写匹配
    return COUNTRY_TRANSLATIONS[country] || COUNTRY_TRANSLATIONS[country.toUpperCase()] || country;
};

